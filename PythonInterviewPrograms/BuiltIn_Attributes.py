# This program describes about Built In Attributes
a = 10
b = 20
c = 30
print(a)
print(b)
print(c)

# In single print statement with separator
print(a,b,c)

# In Single print statement with separator ,
print(a,b,c,sep='-')

# In single print statement with end built-in attribute
print(a,end=" ,")
print(b,end=" ,")
print(c)